// Merge base + page translations
const translations: Record<Locale, Record<string, string>> = {} as any;
const allLocales: Locale[] = ["ko", "en", "es", "zh", "ja", "fr", "de", "ar", "id", "pt", "hi"];
for (const loc of allLocales) {
  translations[loc] = { ...baseTranslations[loc], ...pageTranslations[loc] };
}

const localeMap: Record<string, Locale> = {
  ko: "ko", en: "en", es: "es", zh: "zh", ja: "ja",
  fr: "fr", de: "de", ar: "ar", id: "id", pt: "pt", hi: "hi",
};

function detectLocale(): Locale {
  const langs = navigator.languages || [navigator.language];
  for (const lang of langs) {
    const code = lang.toLowerCase().split("-")[0];
    if (localeMap[code]) return localeMap[code];
  }
  return "en";
}

export function getDefaultLocale(): Locale {
  return detectLocale();
}

let currentLocale: Locale | null = null;

export function getLocale(): Locale {
  if (!currentLocale) currentLocale = detectLocale();
  return currentLocale;
}

export function setLocale(locale: Locale) {
  currentLocale = locale;
}

export function t(key: string): string {
  const locale = getLocale();
  return translations[locale]?.[key] ?? translations.en[key] ?? key;
}

export function isRTL(): boolean {
  return getLocale() === "ar";
}

